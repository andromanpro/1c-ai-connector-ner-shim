"""Красная проба тестов сервиса: каждый мутант возвращает известную ошибку, test_shim.py обязан упасть.

    uv run python mutants_shim.py

Мутант убит, если упали все его ожидаемые проверки и упали не все проверки (иначе сломан сам прогон).
"""
import pathlib
import re
import shutil
import subprocess
import sys

sys.stdout.reconfigure(encoding="utf-8")
ЗДЕСЬ = pathlib.Path(__file__).parent
ИСХОДНИК = ЗДЕСЬ / "shim.py"

МУТАНТЫ = [
    ("хвост обрезается молча",
     """            if len(текст) > МАКС_СИМВОЛОВ:
                self._ответ(413, {"ok": False, "error": "text too large"})
                return
            self._ответ(200, {"ok": True, "entities": распознать(текст)})""",
     """            self._ответ(200, {"ok": True, "entities": распознать(текст[:МАКС_СИМВОЛОВ])})""",
     ["HTTP: текст длиннее лимита - отказ, а не проверка начала"]),
    ("тело не проверяется на объект",
     """            if not isinstance(запрос, dict) or not isinstance(запрос.get("text"), str):""",
     """            if not isinstance(запрос.get("text"), str):""",
     ["HTTP: тело не объект - 400"]),
    ("отрицательная длина читается",
     """            if длина < 0:""",
     """            if длина < -1:""",
     ["HTTP: отрицательная длина - 400"]),
    ("род фамилии не определяется",
     """    роды = {р.tag.gender for р in _СЛОВАРЬ.parse(фамилия) if "Surn" in р.tag}""",
     """    роды = set()""",
     ["одиночная женская фамилия в падеже - женский род"]),
    ("спан имени не сужается",
     """            начало, конец = _границы_имени(значение, факт, начало, конец)""",
     """            pass""",
     ["глагол в начале предложения не входит в имя"]),
    ("склейка через перевод строки и сужение склейки",
     """        if факт and кусков == 1:""",
     """        if факт:""",
     ["люди списком через перевод строки - никто не потерян"]),
    ("неоднозначный род берется по первому разбору",
     """    if роды == {"femn"}:""",
     """    if "femn" in роды:""",
     ["фамилия с неоднозначным родом - род пустой"]),
]


def прогнать():
    вывод = subprocess.run(["uv", "run", "python", "test_shim.py"], cwd=ЗДЕСЬ, capture_output=True,
                           timeout=600).stdout.decode("utf-8", "replace")
    упали = set(re.findall(r"^СБОЙ (.+?)(?: \||$)", вывод, re.M))
    всего = len(re.findall(r"^(?:ok  |СБОЙ) ", вывод, re.M))
    return упали, всего


исходный = ИСХОДНИК.read_text(encoding="utf-8")
копия = ЗДЕСЬ / "shim.py.исходный"
shutil.copyfile(ИСХОДНИК, копия)
живые = []
try:
    for имя, было, стало, ожидаемые in МУТАНТЫ:
        if исходный.count(было) != 1:
            print(f"[{имя}] якорь найден {исходный.count(было)} раз - мутант не применен")
            живые.append(имя)
            continue
        ИСХОДНИК.write_text(исходный.replace(было, стало), encoding="utf-8")
        упали, всего = прогнать()
        пропущены = [о for о in ожидаемые if о not in упали]
        убит = not пропущены and 0 < len(упали) < всего
        print(f"[{имя}] {'убит' if убит else 'ЖИВ'}: упали {sorted(упали)}"
              + (f"; не упали {пропущены}" if пропущены else ""))
        if not убит:
            живые.append(имя)
finally:
    shutil.copyfile(копия, ИСХОДНИК)
    копия.unlink()
упали, всего = прогнать()
print(f"исходник возвращен: проверок {всего}, сбоев {len(упали)}")
print("живых мутантов:", len(живые), живые)
sys.exit(1 if живые or упали else 0)
