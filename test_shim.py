"""Тесты сервиса: uv run python test_shim.py (без pytest, код выхода 1 при сбое).

Распознавание проверяется напрямую, протокол - через настоящий HTTP-сервер на свободном порту.
"""
import http.client
import json
import sys
import threading
from http.server import ThreadingHTTPServer

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
import shim  # noqa: E402
from shim import распознать  # noqa: E402

сбоев = 0


def проверить(имя, условие, подробности=""):
    global сбоев
    print(("ok   " if условие else "СБОЙ ") + имя + ("" if условие else f" | {подробности}"))
    сбоев += 0 if условие else 1


def найдено(текст, тип):
    return [с for с in распознать(текст) if с["type"] == тип]


# ФИО: склейка частей, порядок, род
с = найдено("Менеджер Петрова Анна написала вчера", "ФИО")
проверить("имя из двух частей - одна сущность", [x["text"] for x in с] == ["Петрова Анна"], с)
проверить("порядок фамилия-имя", с and с[0]["form"] == "LF", с)
проверить("женский род по имени", с and с[0]["gender"] == "f", с)
с = найдено("Позвоните Иванову по поводу оплаты", "ФИО")
проверить("одиночная фамилия в падеже", [x["text"] for x in с] == ["Иванову"], с)
с = найдено("Договор подписал Сидоров Петр Николаевич", "ФИО")
проверить("полное ФИО, мужской род", с and с[0]["form"] == "LFM" and с[0]["gender"] == "m", с)
с = найдено("Передайте Петровой, что счет оплачен", "ФИО")
проверить("одиночная женская фамилия в падеже - женский род", с and с[0]["gender"] == "f", с)
проверить("глагол в начале предложения не входит в имя", [x["text"] for x in с] == ["Петровой"], с)
с = найдено("Позвоните Иванову по поводу оплаты", "ФИО")
проверить("фамилия с неоднозначным родом - род пустой", с and с[0]["gender"] == "", с)
с = найдено("Ответственные:\nПетрова Анна\nСидорова Елена\nКозлов Игорь", "ФИО")
тексты = " | ".join(x["text"] for x in с)
проверить("люди списком через перевод строки - никто не потерян",
          all(ф in тексты for ф in ("Петрова", "Сидорова", "Козлов")), с)

# Организации: только с правовой формой
с = найдено("Не проходит оплата клиента ООО «Ромашка», сервер Microsoft SQL", "ОРГАНИЗАЦИЯ")
проверить("организация с правовой формой", [x["text"] for x in с] == ["ООО «Ромашка»"], с)
проверить("вендор без правовой формы - не организация клиента",
          not найдено("Ошибка в драйвере Microsoft, обновите платформу 1С", "ОРГАНИЗАЦИЯ"))

# Адреса: улица и дом склеиваются, город один - не адрес
с = найдено("Адрес доставки: г. Казань, ул. Баумана, д. 5, кв. 12. Звонить заранее", "АДРЕС")
проверить("адрес одной сущностью", len(с) == 1 and "Баумана" in с[0]["text"] and "12" in с[0]["text"], с)
проверить("город без улицы - не персональные данные", not найдено("Склад в г. Казань закрыт на инвентаризацию", "АДРЕС"))

# Даты: только дата рождения
проверить("дата рождения по слову рядом",
          [x["text"] for x in найдено("Дата рождения 12.03.1985, паспорт выдан", "ДАТАРОЖДЕНИЯ")] == ["12.03.1985"])
проверить("дата документа - не дата рождения", not найдено("Документ от 12.03.2025 не проведен", "ДАТАРОЖДЕНИЯ"))

# Эмодзи не ломают разбор (Telegram)
с = найдено("🤖 Анализ ИИ: клиент Петрова Анна Сергеевна ждет звонка", "ФИО")
проверить("эмодзи перед текстом", [x["text"] for x in с] == ["Петрова Анна Сергеевна"], с)

# Протокол: настоящий сервер, лимит уменьшен, чтобы проверить отказ вместо обрезания хвоста
shim.МАКС_СИМВОЛОВ = 40
shim.Обработчик.timeout = 3  # зависшее чтение тела всплывает за секунды, а не за 30
сервер = ThreadingHTTPServer(("127.0.0.1", 0), shim.Обработчик)
threading.Thread(target=сервер.serve_forever, daemon=True).start()


def запрос(тело, заголовки=None):
    """Код и JSON ответа; сбой соединения - код 0, чтобы проверка напечатала СБОЙ, а не уронила прогон."""
    соединение = http.client.HTTPConnection("127.0.0.1", сервер.server_address[1], timeout=15)
    данные = тело if isinstance(тело, bytes) else json.dumps(тело, ensure_ascii=False).encode("utf-8")
    try:
        соединение.request("POST", "/detect", body=данные,
                           headers=заголовки or {"Content-Type": "application/json"})
        ответ = соединение.getresponse()
        return ответ.status, json.loads(ответ.read().decode("utf-8"))
    except (OSError, ValueError) as ошибка:
        return 0, {"ok": None, "error": repr(ошибка)}
    finally:
        соединение.close()


код, ответ = запрос({"text": "Менеджер Петрова Анна"})
проверить("HTTP: имя найдено", код == 200 and ответ["ok"] and [с["text"] for с in ответ["entities"]] == ["Петрова Анна"],
          (код, ответ))
код, ответ = запрос({"text": "ok " * 10 + "  Петрова Анна"})
проверить("HTTP: текст длиннее лимита - отказ, а не проверка начала", код == 413 and not ответ["ok"], (код, ответ))
код, ответ = запрос([])
проверить("HTTP: тело не объект - 400", код == 400 and not ответ["ok"], (код, ответ))
код, ответ = запрос({"text": 5})
проверить("HTTP: text не строка - 400", код == 400 and not ответ["ok"], (код, ответ))
код, ответ = запрос(b"{}", {"Content-Type": "application/json", "Content-Length": "-1"})
проверить("HTTP: отрицательная длина - 400", код == 400 and not ответ["ok"], (код, ответ))
сервер.shutdown()

print(f"\nсбоев: {сбоев}")
sys.exit(1 if сбоев else 0)
